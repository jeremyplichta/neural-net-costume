"""Write a trained model as a C header for the ESP32.

    python ml/export_weights.py ml/models/hybrid.npz        # -> firmware/lib/nnforward/src/nn_weights.h
Include it next to nnforward.h:  nn_forward(&NN_WEIGHTS, features, activations);
The header also records which feature mode the model needs (NN_FEATURE_MODE).
"""
import argparse
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "tools"))
from words import LABELS  # noqa: E402

MODE_ENUM = {"mean": "NNF_MODE_MEAN", "contours": "NNF_MODE_CONTOURS", "hybrid": "NNF_MODE_HYBRID",
             "mean_norm": "NNF_MODE_MEAN | NNF_NORMALIZE", "contours_norm": "NNF_MODE_CONTOURS | NNF_NORMALIZE",
             "hybrid_norm": "NNF_MODE_HYBRID | NNF_NORMALIZE"}


def fmt(a):
    return "{" + ", ".join(fmt(x) for x in a) + "}" if a.ndim else f"{float(a):.9g}f"


def header(model_path):
    m = np.load(model_path)
    mode = str(m["mode"])
    labels = ", ".join(f'"{l}"' for l in LABELS)
    return f"""/* Generated by ml/export_weights.py from {Path(model_path).name}. Do not edit. */
#ifndef NN_WEIGHTS_H
#define NN_WEIGHTS_H
#include "nnfeatures.h"
#include "nnforward.h"

/* Extract features with nnf_extract(..., NN_FEATURE_MODE, ...) before nn_forward(). */
#define NN_FEATURE_MODE {MODE_ENUM[mode]}
static const char *const NN_LABELS[NN_N] = {{{labels}}};

static const nn_weights_t NN_WEIGHTS = {{
    {fmt(m["mean"])},
    {fmt(m["std"])},
    {fmt(m["W"])},
    {fmt(m["b"])}
}};
#endif
"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("model", type=Path)
    ap.add_argument("--out", type=Path,
                    default=HERE.parent / "firmware" / "lib" / "nnforward" / "src" / "nn_weights.h")
    args = ap.parse_args()
    args.out.write_text(header(args.model))
    print(f"wrote {args.out}")
